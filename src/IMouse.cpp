#include "tiage/IMouse.h"

namespace tiage {

// --------------------------------------------------------------------------------------------------

void
IMouse::update() {
	lastPos_ = currentPos_;
	last_ = current_;
	current_.reset();
	doUpdate();
}
// --------------------------------------------------------------------------------------------------

Vec2<size_t>
IMouse::getPos() {
	return currentPos_;
}

// --------------------------------------------------------------------------------------------------

Vec2<size_t>
IMouse::getLastPos() {
	return lastPos_;
}

// --------------------------------------------------------------------------------------------------

bool
IMouse::pressed(int key) const {
	return current_[key] && !last_[key];
}
// --------------------------------------------------------------------------------------------------

bool
IMouse::released(int key) const {
	return !current_[key] && last_[key];
}

// --------------------------------------------------------------------------------------------------

bool
IMouse::holding(int key) const {
	return current_[key];
}

// --------------------------------------------------------------------------------------------------

void 
IMouse::setKey(int key) {
	current_[key] = 1;
}

// --------------------------------------------------------------------------------------------------

void 
IMouse::setPos(Vec2<size_t> pos) {
	currentPos_ = pos;
}

// --------------------------------------------------------------------------------------------------

} // tiage
